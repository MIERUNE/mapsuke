# Locale prefix (the language part of the QGIS locale, e.g. "ja" for ja_JP) -> dictionary.
LANGUAGES = {"ja": JA, "tr": TR}


def ui_locale():
    try:
        from qgis.PyQt.QtCore import QLocale, QSettings
    except ImportError:
        return locale.getlocale()[0] or ""
    settings = QSettings()
    if settings.value("locale/overrideFlag", False, type=bool):
        selected = settings.value("locale/userLocale", "")
        if selected:
            return selected
    try:
        from qgis.core import QgsApplication
        application = QgsApplication.instance()
        if application:
            return application.locale()
    except (ImportError, AttributeError):
        pass
    return QLocale.system().name()


def ui_language():
    """The LANGUAGES key matching QGIS's interface locale, or "" for English."""
    name = ui_locale().lower().replace("-", "_").split("_")[0]
    return name if name in LANGUAGES else ""


def tr(source):
    table = LANGUAGES.get(ui_language())
    return (table.get(source) or source) if table else source
